# Bash Script Tasks

## Environment

- Operating System: Amazon Linux 2023
- Platform: AWS EC2
- Shell: Bash

## Bash Script Tasks

1. Check if a directory is available or not
2. Create multiple files
3. Take backup of a directory
4. Install Nginx
5. Install Apache Tomcat
6. Check Nginx service and start if not running
7. Bash Calculator
8. Check directory and create if not exists
9. Delete last 3 lines of a file
10. Monitor CPU usage
11. Monitor disk usage
12. Monitor memory usage

## Crontab Exercises

1. April 5th Midnight
2. 5th of November, January and June if Thursday
3. 05 and 27 minutes of 9, 10 and 11 hours every day
4. 34 minutes of 9th hour on 15th August
5. Every midnight
6. Every Saturday at 11:59 PM
7. After every reboot

